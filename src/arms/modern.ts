const found = new Map<string, IconArt>();
for (const def of charges) {
  const icon = def.icon ? icons[def.icon]?.icon : undefined;
  if (icon && typeof icon[4] === 'string') found.set(def.id, { w: icon[0], h: icon[1], d: icon[4] });
}

export const modernArt = (id: string): IconArt | undefined => found.get(id);
